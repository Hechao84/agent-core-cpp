void InitMcpServer()
{
    std::cout << "\nInitializing Amap MCP Server (Streamable HTTP)...\n" << std::flush;
    try {
        std::string amapJson = R"({
            "url": "https://mcp.amap.com",
            "endpoint": "/mcp?key=<YOUR_AMAP_KEY>",
            "isActive": "true",
            "description": "this is a mcp map server",
            "type": "streamable-http-client"
        })";

        auto& rm = ResourceManager::GetInstance();
        rm.RegisterMCPServer("amap", amapJson);

        std::cout << "[SUCCESS] Amap MCP server connected. Available tools:\n" << std::flush;
        auto mcpTools = rm.GetAvailableTools();
        for (const auto& toolName : mcpTools) {
            std::cout << "  - " << toolName << "\n" << std::flush;
        }
    } catch (const std::exception& e) {
        std::cout << "[WARN] MCP Server initialization failed: " << e.what() << "\n" << std::flush;
    }
}

void RunServerMode(const AgentConfig& /* config */)
{
    std::signal(SIGINT, SignalHandler);
    std::signal(SIGTERM, SignalHandler);

    std::cout << "[Server] Starting jiuwenClaw Agent Server...\n" << std::flush;

    WebApi server;
    WebApiConfig webConfig;
    webConfig.host = "127.0.0.1";
    webConfig.port = 8080;
    webConfig.staticDir = "./web";

    server.Start(webConfig);

    std::cout << "[Server] Agent Server running at " << server.GetUrl() << "\n" << std::flush;
    std::cout << "[Server] Open http://" << webConfig.host << ":" << webConfig.port << " in your browser\n" << std::flush;
    std::cout << "[Server] Type '/exit' or press Ctrl+C to stop...\n" << std::flush;

    // Wait for exit command or signal
    while (g_ServerRunning) {
        std::string cmd;
        if (std::getline(std::cin, cmd)) {
            if (cmd == "/exit" || cmd == "exit" || cmd == "quit") {
                g_ServerRunning = false;
                break;
            }
        } else {
            // EOF reached
            break;
        }
    }

    std::cout << "\n[Server] Stopping server...\n" << std::flush;
    server.Stop();
    std::cout << "[Server] Goodbye.\n" << std::flush;
}

void RunCliMode(const AgentConfig& /* config */)
{
    std::cout << "\nEnter '/exit' to quit, '/session <id>' to switch session.\n" << std::flush;

    // Session management for CLI
    std::string currentSession = kDefaultSessionId;

    std::string query;
    while (true) {
        std::cout << "[" << currentSession << "]> " << std::flush;
        std::getline(std::cin, query);

        if (query == "/exit") {
            LOG(INFO) << "User input: " << query;
            break;
        }

        if (query.empty()) {
            continue;
        }

        // Handle /session command to switch between sessions
        if (query.substr(0, 9) == "/session ") {
            currentSession = TrimStr(query.substr(9));
            if (currentSession.empty()) {
                currentSession = kDefaultSessionId;
            }
            // Create session via SessionManager
            GetSessionManager().GetOrCreateSession(currentSession);
            LOG(INFO) << "[CLI] Switched to session: " << currentSession;
            std::cout << "[Info] Switched to session: " << currentSession << "\n";
            continue;
        }

        // Handle /sessions command to list active sessions
        if (query == "/sessions") {
            auto ids = GetSessionManager().GetSessionIds();
            std::cout << "Active sessions (" << ids.size() << "): ";
            for (size_t i = 0; i < ids.size(); ++i) {
                if (i > 0) std::cout << ", ";
                std::cout << ids[i] << (ids[i] == currentSession ? " (current)" : "");
            }
            std::cout << "\n";
            continue;
        }

        std::string utf8Query = LocalToUTF8(query);
        utf8Query = CleanInput(utf8Query);
        utf8Query = FixUTF8(utf8Query);
        utf8Query = TrimStr(utf8Query);
        if (utf8Query.empty()) {
            continue;
        }

        std::cout << "Processing...\n";

        std::string utf8Carry;

        const std::string TAG_STREAM = "[STREAM]";
        const std::string TAG_STATUS = "[STATUS]";
        const std::string TAG_TOOL_CALLS = "[TOOL_CALLS]";
        const std::string TAG_TOOL_RESPONSE = "[TOOL_RESPONSE]";
        const std::string TAG_FINAL = "[FINAL]";

        // Invoke via SessionManager with per-session lock and concurrency gate
        SessionInvokeResult result = GetSessionManager().Invoke(
            currentSession,
            utf8Query,
            [&](const std::string& resp) {
                if (resp.empty()) return;

                std::string s = resp;
                // 1. Tool calls, content overlaps with streaming, no echo
                if (s.find(TAG_TOOL_CALLS) != std::string::npos) return;

                // 2. Tool response
                if (s.find(TAG_TOOL_RESPONSE) != std::string::npos) {
                    size_t start_pos = s.find(TAG_TOOL_RESPONSE);
                    if (start_pos != std::string::npos) {
                        start_pos += TAG_TOOL_RESPONSE.length();
                        while (start_pos < s.length() && s[start_pos] == ' ') {
                            ++start_pos;
                        }
                        std::string toolRespText = s.substr(start_pos);
                        std::cout << "\n\n**Tool Response**: \n" << UTF8ToLocal(toolRespText) << std::endl;
                    }
                    return;
                }

                // 3. Streaming output
                if (s.find(TAG_STREAM) != std::string::npos) {
                    size_t start_pos = s.find(TAG_STREAM);
                    if (start_pos != std::string::npos) {
                        start_pos += TAG_STREAM.length();
                        while (start_pos < s.length() && s[start_pos] == ' ') {
                            ++start_pos;
                        }
                        std::string cleanText = s.substr(start_pos);

                        if (!cleanText.empty()) {
                            std::string fixed = FixUTF8Streaming(cleanText, utf8Carry);
                            std::cout << UTF8ToLocal(fixed) << std::flush;
                        }
                    }
                    return;
                }

                // 4. Status info
                if (s.find(TAG_STATUS) != std::string::npos) {
                    size_t start_pos = s.find(TAG_STATUS);
                    if (start_pos != std::string::npos) {
                        start_pos += TAG_STATUS.length();
                        while (start_pos < s.length() && s[start_pos] == ' ') {
                            ++start_pos;
                        }
                        std::string statusText = s.substr(start_pos);
                        std::string formattedStatus = "\n>> " + TrimStr(statusText) + "\n";
                        std::cout << UTF8ToLocal(formattedStatus) << std::flush;
                    }
                    return;
                }

                // 5. [FINAL] tag means done, no special handling
                if (s.find(TAG_FINAL) != std::string::npos) return;

                // 6. Fallback: plain text without tag
                if (!s.empty()) {
                    std::cout << UTF8ToLocal(s) << std::flush;
                }
            }
        );

        std::cout << "\n";
    }
}

void PrintUsage()
{
    std::cout << "Usage: jiuwenClaw [OPTIONS]\n"
              << "\n"
              << "Options:\n"
              << "  --server     Start Agent Server with web UI (default: 127.0.0.1:8080)\n"
              << "  --port <N>   Set server port (default: 8080)\n"
              << "  --host <IP>  Set server host (default: 127.0.0.1)\n"
              << "  --cli        Start CLI mode (default)\n"
              << "  --help       Show this help message\n"
              << std::endl;
}

int main(int argc, char* argv[])
{
    std::cout << "jiuwenClaw is an Agent powered by jiuwen-lite Agent Framework\n====================\n" << std::flush;

    bool serverMode = false;
    std::string serverHost = "127.0.0.1";
    int serverPort = 8080;

    // Parse command line arguments
    for (int i = 1; i < argc; ++i) {
        std::string arg = argv[i];
        if (arg == "--server") {
            serverMode = true;
        } else if (arg == "--cli") {
            serverMode = false;
        } else if (arg == "--port" && i + 1 < argc) {
            serverPort = std::stoi(argv[++i]);
        } else if (arg == "--host" && i + 1 < argc) {
            serverHost = argv[++i];
        } else if (arg == "--help") {
            PrintUsage();
            return 0;
        }
    }

    // Register additional tools
    RegisterDemoTools();
    std::cout << "[Boot] Demo tools registered\n" << std::flush;

    // Initialize MCP server
    InitMcpServer();
    std::cout << "[Boot] MCP server initialized\n" << std::flush;

    // Build and initialize SessionManager
    AgentConfig config = BuildAgentConfig();
    std::cout << "[Boot] AgentConfig built\n" << std::flush;
    InitSessionManager(config);
    std::cout << "[Boot] SessionManager initialized\n" << std::flush;

    // Initialize heartbeat and cron using reserved sessions
    HeartbeatManager heartbeat(
        "./data/HEARTBEAT.md",
        config.modelConfig,
        300
    );
    std::cout << "[Boot] HeartbeatManager constructed\n" << std::flush;

    CronWatcher cronWatcher("./data", config.modelConfig, 60);
    std::cout << "[Boot] CronWatcher constructed\n" << std::flush;

    if (serverMode) {
        // Override web config from command line
        WebApiConfig webConfig;
        webConfig.host = serverHost;
        webConfig.port = serverPort;
        webConfig.staticDir = "./web";

        std::cout << "[Boot] Entering RunServerMode\n" << std::flush;
        RunServerMode(config);
    } else {
        RunCliMode(config);
    }

    return 0;
}
