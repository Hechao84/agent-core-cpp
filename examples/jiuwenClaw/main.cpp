void SignalHandler(int signum)
{
    if (signum == SIGINT || signum == SIGTERM) {
        g_Running = false;
    }
}

AgentConfig BuildAgentConfig()
{
    AgentConfig config;
    config.id = "demo-agent";
    config.name = "Demo Agent";
    config.mode = AgentWorkMode::REACT;
    config.maxIterations = 100;

    // Data directory layout
    config.dataBasePath = "./data";

    // Context configuration (session-agnostic, per-session paths are generated by SessionManager)
    config.contextConfig.sessionId = kDefaultSessionId;
    config.contextConfig.storageType = ContextConfig::StorageType::JSON_FILE;
    config.contextConfig.storagePath = ""; // SessionManager will set this per-session

    // Memory configuration: idle poll interval + system sessions excluded
    // from consolidation. Cron / heartbeat events are still persisted for
    // audit but never consolidated into long-term memory, so the memory
    // reflects real user conversations rather than mechanical ticks.
    config.memoryConfig.idleConsolidationSeconds = 60;
    config.memoryConfig.excludedConsolidationSessionIds = {kHeartbeatSessionId, kCronSessionId};

    config.skillDirectory = "./my_skills";

    config.modelConfig.baseUrl = "<YOUR_MODEL_BASE_URL>";
    config.modelConfig.apiKey = "<YOUR_MODEL_API_KEY>";
    config.modelConfig.modelName = "<YOUR_MODEL_NAME>";
    config.modelConfig.formatType = ModelFormatType::OPENAI;

    config.modelConfig.extraParams.Set("max_tokens", 4096);
    config.modelConfig.extraParams.Set("temperature", 0.0f);
    config.modelConfig.extraParams.Set("top_p", 0.0f);
    config.modelConfig.extraParams.Set("tool_choice", std::string("auto"));

    config.promptTemplates["react_system"] = PromptResource{
        PromptResourceType::FILE_PATH,
        "./examples/jiuwenClaw/templates/REACT_SYSTEM.md"
    };

    config.promptTemplates["agents"] = PromptResource{
        PromptResourceType::FILE_PATH,
        "./examples/jiuwenClaw/templates/AGENTS.md"
    };
    config.promptTemplates["soul"] = PromptResource{
        PromptResourceType::FILE_PATH,
        "./examples/jiuwenClaw/templates/SOUL.md"
    };
    config.promptTemplates["user"] = PromptResource{
        PromptResourceType::FILE_PATH,
        "./examples/jiuwenClaw/templates/USER.md"
    };
    config.promptTemplates["tools_md"] = PromptResource{
        PromptResourceType::FILE_PATH,
        "./examples/jiuwenClaw/templates/TOOLS.md"
    };

    // Default tools for all sessions
    auto& rm = ResourceManager::GetInstance();
    auto allTools = rm.GetAvailableTools();
    config.defaultTools = allTools;

    return config;
}

