int main(int argc, char* argv[])
{
    std::cout << "jiuwenClaw - Agent powered by jiuwen-lite Agent Framework\n====================\n" << std::flush;

    bool enableServer = false;
    bool enableCli = true;
    bool enableWatch = false;
    std::string serverHost = "127.0.0.1";
    int serverPort = 8080;

    // Parse command line arguments
    for (int i = 1; i < argc; ++i) {
        std::string arg = argv[i];
        if (arg == "--server") {
            enableServer = true;
        } else if (arg == "--no-cli") {
            enableCli = false;
        } else if (arg == "--watch-config") {
            enableWatch = true;
        } else if (arg == "--port" && i + 1 < argc) {
            serverPort = std::stoi(argv[++i]);
        } else if (arg == "--host" && i + 1 < argc) {
            serverHost = argv[++i];
        } else if (arg == "--help") {
            PrintUsage();
            return 0;
        }
    }

    // Register additional tools
    RegisterDemoTools();
    std::cout << "[Boot] Demo tools registered\n" << std::flush;

    // Build the hard-coded default (kept for backward compatibility)
    AgentConfig defaultConfig = BuildAgentConfig();
    std::cout << "[Boot] Default AgentConfig built (id=" << defaultConfig.id << ")\n" << std::flush;

    // Register the default in the config store, then load + merge agents.json.
    auto& cfgStore = AgentConfigStore::Instance();
    cfgStore.SetPersistPath("./data/agents.json");
    cfgStore.RegisterDefault(defaultConfig);
    auto effective = cfgStore.Load();

    // Use the merged config for the primary agent id.
    AgentConfig config = defaultConfig;
    auto it = effective.find(defaultConfig.id);
    if (it != effective.end()) {
        config = it->second;
        std::cout << "[Boot] Effective AgentConfig (default + agents.json overrides) ready\n"
                  << std::flush;
    } else {
        std::cout << "[Boot] No override in agents.json; using code default\n" << std::flush;
    }

    InitSessionManager(config);
    std::cout << "[Boot] SessionManager initialized\n" << std::flush;

    // Register application-layer reserved sessions with the core library so
    // they cannot be deleted via /api/sessions DELETE. The core library
    // already auto-registers __DEFAULT__ (its own MakeSessionKey fallback);
    // jiuwenClaw additionally protects __HEARTBEAT__ and __CRON__ here. The
    // same ids are listed in MemoryConfig::excludedConsolidationSessionIds
    // (set in BuildAgentConfig) so memory consolidation skips their events.
    GetSessionManager().RegisterReservedSession(kHeartbeatSessionId);
    GetSessionManager().RegisterReservedSession(kCronSessionId);
    std::cout << "[Boot] Reserved sessions registered (__HEARTBEAT__, __CRON__)\n" << std::flush;

    // Load MCP servers from the application-layer registry (mcp_servers.json).
    // The framework itself only knows how to register/connect McpServerConfig
    // objects; it does not care where those configs come from. Other apps
    // can supply them via hard-coded values or their own config loader.
    {
        auto& mcpMgr = McpServerManager::GetInstance();
        mcpMgr.SetPersistPath("./data/mcp_servers.json");
        mcpMgr.Load(); // tolerate missing file (empty pool is a valid state)
        auto configs = mcpMgr.ToFrameworkConfigs();
        if (!configs.empty()) {
            ResourceManager::GetInstance().LoadMCPServers(configs);
            // Sync MCP-discovered tools into the Agent so they appear in the prompt
            if (auto agent = GetSessionManager().GetAgent()) {
                int n = agent->SyncMcpTools();
                std::cout << "[Boot] Synced " << n << " MCP tool(s) to Agent\n" << std::flush;
            }
            std::cout << "[Boot] Loaded " << configs.size()
                      << " MCP server(s) from mcp_servers.json\n" << std::flush;
        } else {
            std::cout << "[Boot] No MCP servers configured (edit ./data/mcp_servers.json or use the web UI to add)\n"
                      << std::flush;
        }
    }

    // Initialize heartbeat and cron using reserved sessions.
    // Held in unique_ptr so they can be stopped (and their threads joined)
    // deterministically in the shutdown section, before SessionManager is
    // drained, rather than at end-of-main stack unwinding.
    auto heartbeat = std::make_unique<HeartbeatManager>(
        "./data/HEARTBEAT.md",
        config.modelConfig,
        300
    );
    std::cout << "[Boot] HeartbeatManager constructed\n" << std::flush;

    auto cronWatcher = std::make_unique<CronWatcher>("./data", config.modelConfig, 60);
    std::cout << "[Boot] CronWatcher constructed\n" << std::flush;

    // Start HTTP server if enabled
    if (enableServer) {
        g_HttpServer = std::make_unique<HttpServer>();
        HttpServerConfig httpConfig;
        httpConfig.host = serverHost;
        httpConfig.port = serverPort;
        httpConfig.staticDir = "./examples/jiuwenClaw/web";
        g_HttpServer->Start(httpConfig);
        std::cout << "[Boot] HTTP server started at " << serverHost << ":" << serverPort << "\n" << std::flush;

        // Load channels from disk and start each enabled channel via ChannelService
        auto& channelMgr = ChannelManager::GetInstance();
        channelMgr.SetPersistPath("./data/channels.json");
        channelMgr.Load();
        ChannelService::Instance().StartAll();
        auto active = ChannelService::Instance().ActiveIds();
        if (active.empty()) {
            std::cout << "[Boot] No channels active (edit ./data/channels.json or use the web UI to add)\n"
                      << std::flush;
        } else {
            std::cout << "[Boot] Active channels: " << active.size() << "\n" << std::flush;
        }
    }

    // Optional config-file watcher: auto-reload on disk change
    if (enableWatch) {
        g_ConfigWatcher = std::make_unique<ConfigWatcher>();
        g_ConfigWatcher->Watch("./data/agents.json", [](const std::string& p) {
            (void)p;
            LOG(INFO) << "[Watch] agents.json changed -> hot-reload";
            ReloadAgent("");
        });
        g_ConfigWatcher->Watch("./data/channels.json", [](const std::string& p) {
            (void)p;
            LOG(INFO) << "[Watch] channels.json changed -> reconcile";
            ReloadChannels();
        });
        g_ConfigWatcher->Watch("./data/mcp_servers.json", [](const std::string& p) {
            (void)p;
            LOG(INFO) << "[Watch] mcp_servers.json changed -> reload MCP pool";
            auto& mcpMgr = McpServerManager::GetInstance();
            mcpMgr.Load();
            ResourceManager::GetInstance().LoadMCPServers(mcpMgr.ToFrameworkConfigs());
            // Sync discovered tools to live Agent
            if (auto agent = GetSessionManager().GetAgent()) {
                agent->SyncMcpTools();
            }
        });
        g_ConfigWatcher->Start(3);
        std::cout << "[Boot] Config watcher enabled (poll every 3s)\n" << std::flush;
    }

    std::signal(SIGINT, SignalHandler);
    std::signal(SIGTERM, SignalHandler);

    if (enableCli) {
        RunCliMode();
    } else {
        // Daemon mode: wait for signal
        std::cout << "[Boot] Running in daemon mode. Press Ctrl+C to stop...\n" << std::flush;
        while (g_Running) {
            std::this_thread::sleep_for(std::chrono::seconds(1));
        }
    }

    // Cleanup
    std::cout << "\n[Shutdown] Stopping services...\n" << std::flush;

    if (g_ConfigWatcher) {
        g_ConfigWatcher->Stop();
        g_ConfigWatcher.reset();
    }

    ChannelService::Instance().StopAll();

    if (g_HttpServer) {
        g_HttpServer->Stop();
        g_HttpServer.reset();
    }

    // Stop the background schedulers BEFORE draining the SessionManager so that
    // no thread can call into it afterwards. Each reset() joins its worker
    // thread (waiting for any in-flight Invoke to finish).
    cronWatcher.reset();
    heartbeat.reset();

    // Gracefully stop the Agent's consolidation thread. The singleton itself is
    // never deleted (its memory is reclaimed at process exit); this only drains
    // background work so it is joined deterministically here.
    GetSessionManager().Shutdown();

    std::cout << "[Shutdown] Goodbye.\n" << std::flush;

    return 0;
}
