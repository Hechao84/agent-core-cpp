void RunCliMode()
{
    std::cout << "\nEnter '/exit' to quit, '/session <id>' to switch session.\n" << std::flush;

    // Session management for CLI
    std::string currentSession = kDefaultSessionId;

    std::string query;
    while (g_Running) {
        std::cout << "[" << currentSession << "]> " << std::flush;
        if (!std::getline(std::cin, query)) {
            break;
        }

        if (query == "/exit") {
            LOG(INFO) << "User input: " << query;
            g_Running = false;
            break;
        }

        if (query.empty()) {
            continue;
        }

        // Handle /session command to switch between sessions
        if (query.substr(0, 9) == "/session ") {
            currentSession = TrimStr(query.substr(9));
            if (currentSession.empty()) {
                currentSession = kDefaultSessionId;
            }
            // Create session via SessionManager
            GetSessionManager().GetOrCreateSession(currentSession);
            LOG(INFO) << "[CLI] Switched to session: " << currentSession;
            std::cout << "[Info] Switched to session: " << currentSession << "\n";
            continue;
        }

        // Handle /sessions command to list active sessions
        if (query == "/sessions") {
            auto ids = GetSessionManager().GetSessionIds();
            std::cout << "Active sessions (" << ids.size() << "): ";
            for (size_t i = 0; i < ids.size(); ++i) {
                if (i > 0) {
                    std::cout << ", ";
                }
                std::cout << ids[i] << (ids[i] == currentSession ? " (current)" : "");
            }
            std::cout << "\n";
            continue;
        }

        // Handle /reload [agent [<id>] | channels]
        if (query == "/reload" || query.substr(0, 8) == "/reload ") {
            std::string rest = query.length() > 8 ? TrimStr(query.substr(8)) : "";
            if (rest.empty()) {
                std::cout << "[Reload] Reloading agents.json and channels.json...\n";
                ReloadAll();
                std::cout << "[Reload] Done.\n";
            } else if (rest == "channels") {
                std::cout << "[Reload] Reconciling channels...\n";
                ReloadChannels();
                std::cout << "[Reload] Done.\n";
            } else if (rest.substr(0, 5) == "agent") {
                std::string id = rest.length() > 6 ? TrimStr(rest.substr(6)) : "";
                std::cout << "[Reload] Reloading agent '" << (id.empty() ? "<default>" : id) << "'...\n";
                bool ok = ReloadAgent(id);
                std::cout << (ok ? "[Reload] Done.\n" : "[Reload] Failed (see logs).\n");
            } else {
                std::cout << "Usage: /reload | /reload agent [<id>] | /reload channels\n";
            }
            continue;
        }

        // Handle /config show [<id>]
        if (query == "/config show" || query.substr(0, 13) == "/config show ") {
            std::string id = query.length() > 13 ? TrimStr(query.substr(13)) : "";
            if (id.empty()) {
                id = GetSessionManager().GetConfig().id;
            }
            auto cfgOpt = AgentConfigStore::Instance().Get(id);
            if (!cfgOpt) {
                std::cout << "[Config] No agent with id=" << id << "\n";
            } else {
                std::cout << AgentConfigToJson(*cfgOpt).dump(2) << "\n";
            }
            continue;
        }

        std::string utf8Query = LocalToUTF8(query);
        utf8Query = CleanInput(utf8Query);
        utf8Query = FixUTF8(utf8Query);
        utf8Query = TrimStr(utf8Query);
        if (utf8Query.empty()) {
            continue;
        }

        std::cout << "Processing...\n";

        std::string utf8Carry;
        bool gotStreamText = false;

        const std::string TAG_STREAM = "[STREAM]";
        const std::string TAG_STATUS = "[STATUS]";
        const std::string TAG_TOOL_CALLS = "[TOOL_CALLS]";
        const std::string TAG_TOOL_RESPONSE = "[TOOL_RESPONSE";  // closing ']' may include call id
        const std::string TAG_FINAL = "[FINAL]";
        const std::string TAG_ASK_USER = "[ASK_USER]";
        const std::string TAG_ASK_USER_END = "[/ASK_USER]";

        // Invoke via SessionManager with per-session lock and concurrency gate
        SessionInvokeResult result = GetSessionManager().Invoke(
            currentSession,
            utf8Query,
            [&](const std::string& resp) {
                if (resp.empty()) {
                    return;
                }

                std::string s = resp;
                // 0. Ask-user prompt: spawn a detached helper that reads
                // stdin and calls Agent::ProvideUserResponse so the worker
                // thread (currently blocked in AskUserTool::Invoke) can wake
                // up. The callback itself must return immediately, otherwise
                // streaming would be stalled.
                if (s.find(TAG_ASK_USER) != std::string::npos) {
                    size_t start = s.find(TAG_ASK_USER);
                    size_t end = s.find(TAG_ASK_USER_END, start);
                    if (end != std::string::npos) {
                        std::string payload = s.substr(start + TAG_ASK_USER.length(),
                                                       end - start - TAG_ASK_USER.length());
                        try {
                            auto j = nlohmann::json::parse(payload);
                            std::string requestId = j.value("request_id", std::string{});
                            std::string question = j.value("question", std::string{});
                            bool multiple = j.value("multiple", false);
                            std::vector<std::string> options;
                            if (j.contains("options") && j["options"].is_array()) {
                                for (const auto& v : j["options"]) {
                                    if (v.is_string()) {
                                        options.push_back(v.get<std::string>());
                                    }
                                }
                            }
                            if (!requestId.empty()) {
                                std::thread([requestId, question, options, multiple]() {
                                    std::cout << "\n\n[Agent 询问] " << question << "\n";
                                    if (!options.empty()) {
                                        for (size_t i = 0; i < options.size(); ++i) {
                                            std::cout << "  [" << (i + 1) << "] " << options[i] << "\n";
                                        }
                                        std::cout << (multiple ? "请输入编号（多选用逗号分隔，留空跳过，60s 超时）: "
                                                                : "请输入编号（留空跳过，60s 超时）: ");
                                    } else {
                                        std::cout << "请输入答复（留空跳过，60s 超时）: ";
                                    }
                                    std::cout.flush();
                                    std::string line;
                                    if (!std::getline(std::cin, line)) {
                                        line.clear();
                                    }
                                    std::string answer;
                                    if (!options.empty() && !line.empty()) {
                                        // Map 1-based indexes to option labels
                                        std::vector<std::string> picks;
                                        std::stringstream ss(line);
                                        std::string item;
                                        while (std::getline(ss, item, ',')) {
                                            try {
                                                int idx = std::stoi(TrimStr(item));
                                                if (idx >= 1 && static_cast<size_t>(idx) <= options.size()) {
                                                    picks.push_back(options[idx - 1]);
                                                }
                                            } catch (...) {
                                                // Treat as free text if it is not a number
                                                picks.push_back(TrimStr(item));
                                            }
                                            if (!multiple && !picks.empty()) {
                                                break;
                                            }
                                        }
                                        nlohmann::json ans;
                                        ans["answers"] = picks;
                                        answer = ans.dump();
                                    } else {
                                        nlohmann::json ans;
                                        ans["text"] = line;
                                        answer = ans.dump();
                                    }
                                    if (auto agent = GetSessionManager().GetAgent()) {
                                        GetSessionManager().ProvideUserResponse(requestId, answer);
                                    }
                                }).detach();
                            }
                        } catch (const std::exception& e) {
                            LOG(WARN) << "[CLI] Failed to parse ASK_USER payload: " << e.what();
                        }
                    }
                    return;
                }

                // 1. Tool calls, content overlaps with streaming, print call metadata
                if (s.find(TAG_TOOL_CALLS) != std::string::npos) {
                    size_t start_pos = s.find(TAG_TOOL_CALLS);
                    start_pos += TAG_TOOL_CALLS.length();
                    while (start_pos < s.length() && (s[start_pos] == ' ' || s[start_pos] == '\n')) {
                        ++start_pos;
                    }
                    std::string payload = TrimStr(s.substr(start_pos));
                    try {
                        auto j = nlohmann::json::parse(payload);
                        std::string callId = j.value("id", std::string{});
                        std::string name = j.value("name", std::string{"tool"});
                        std::string argsText;
                        if (j.contains("arguments")) {
                            if (j["arguments"].is_string()) {
                                argsText = j["arguments"].get<std::string>();
                            } else {
                                argsText = j["arguments"].dump(2);
                            }
                        }
                        std::cout << "\n\n**Tool Call**:\n";
                        if (!callId.empty()) {
                            std::cout << "ID: " << UTF8ToLocal(callId) << "\n";
                        }
                        std::cout << "Name: " << UTF8ToLocal(name) << "\n";
                        if (!argsText.empty()) {
                            std::cout << "Arguments:\n" << UTF8ToLocal(argsText) << "\n";
                        }
                    } catch (const std::exception&) {
                        std::cout << "\n\n**Tool Call**:\n" << UTF8ToLocal(payload) << "\n";
                    }
                    return;
                }

                // 2. Tool response (supports [TOOL_RESPONSE] and [TOOL_RESPONSE <call_id>])
                if (s.find(TAG_TOOL_RESPONSE) != std::string::npos) {
                    size_t start_pos = s.find(TAG_TOOL_RESPONSE);
                    if (start_pos != std::string::npos) {
                        size_t close = s.find(']', start_pos);
                        if (close != std::string::npos) {
                            start_pos = close + 1;
                            while (start_pos < s.length() && s[start_pos] == ' ') {
                                ++start_pos;
                            }
                            std::string toolRespText = s.substr(start_pos);
                            std::cout << "\n\n**Tool Response**: \n" << UTF8ToLocal(toolRespText) << std::endl;
                        }
                    }
                    return;
                }

                // 3. Streaming output
                if (s.find(TAG_STREAM) != std::string::npos) {
                    size_t start_pos = s.find(TAG_STREAM);
                    if (start_pos != std::string::npos) {
                        start_pos += TAG_STREAM.length();
                        std::string cleanText = s.substr(start_pos);

                        if (!cleanText.empty()) {
                            gotStreamText = true;
                            std::string fixed = FixUTF8Streaming(cleanText, utf8Carry);
                            std::cout << UTF8ToLocal(fixed) << std::flush;
                        }
                    }
                    return;
                }

                // 4. Status info
                if (s.find(TAG_STATUS) != std::string::npos) {
                    size_t start_pos = s.find(TAG_STATUS);
                    if (start_pos != std::string::npos) {
                        start_pos += TAG_STATUS.length();
                        while (start_pos < s.length() && s[start_pos] == ' ') {
                            ++start_pos;
                        }
                        std::string statusText = s.substr(start_pos);
                        std::string formattedStatus = "\n>> " + TrimStr(statusText) + "\n";
                        std::cout << UTF8ToLocal(formattedStatus) << std::flush;
                    }
                    return;
                }

                // 5. [FINAL] carries the final answer. When the model already
                // streamed its tokens they were printed above; otherwise (e.g.
                // a retry path where streaming was suppressed) display the
                // carried text here so the answer is never lost.
                if (s.find(TAG_FINAL) != std::string::npos) {
                    if (!gotStreamText) {
                        size_t pos = s.find(TAG_FINAL);
                        if (pos != std::string::npos) {
                            pos += TAG_FINAL.length();
                            while (pos < s.length() && s[pos] == ' ') ++pos;
                            std::string finalText = s.substr(pos);
                            while (!finalText.empty() && (finalText.back() == '\n' || finalText.back() == '\r')) {
                                finalText.pop_back();
                            }
                            if (!finalText.empty()) {
                                std::cout << UTF8ToLocal(finalText) << std::flush;
                            }
                        }
                    }
                    return;
                }

                // 6. Fallback: plain text without tag
                if (!s.empty()) {
                    std::cout << UTF8ToLocal(s) << std::flush;
                }
            }
        );

        std::cout << "\n";
    }
}

// === Hot-reload helpers ===

// Reload one agent by id (default = current SessionManager config id).
// Returns true on success, false on error (e.g. id not found).
bool ReloadAgent(const std::string& agentId)
{
    auto& store = AgentConfigStore::Instance();
    store.Load(); // Re-read agents.json (merged with defaults)

    std::string id = agentId;
    if (id.empty()) {
        id = GetSessionManager().GetConfig().id;
        if (id.empty()) {
            id = "demo-agent";
        }
    }

    auto cfgOpt = store.Get(id);
    if (!cfgOpt) {
        LOG(ERR) << "[Reload] No agent found with id=" << id;
        return false;
    }

    std::string err;
    if (GetSessionManager().ReloadAgent(*cfgOpt, &err)) {
        LOG(INFO) << "[Reload] Agent '" << id << "' hot-reloaded successfully";
        return true;
    }
    LOG(ERR) << "[Reload] Hot-reload failed for '" << id << "': " << err;
    return false;
}

void ReloadChannels()
{
    auto& mgr = ChannelManager::GetInstance();
    mgr.Load(); // re-read channels.json
    ChannelService::Instance().ReconcileAll();
    LOG(INFO) << "[Reload] Channels reconciled";
}

void ReloadAll()
{
    ReloadAgent("");
    ReloadChannels();
}

